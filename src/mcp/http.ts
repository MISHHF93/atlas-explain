/**
 * The ATLAS Explain MCP server over HTTP (MCP "Streamable HTTP" transport), so AI assistants
 * connect with a web address instead of a download. Stateless and read-only: every POST
 * carries one JSON-RPC message and gets one JSON answer; there is no session and no stream.
 * Hosted on Cloudflare Workers' free plan (src/mcp/worker.ts); see docs/MCP.md.
 */
import { ICON_PNG_512_BASE64, ICON_PNG_64_BASE64, ICON_SVG } from "./icon-data";
import { eventOf, type CallEvent } from "./stats";
import { ALL_PROTOCOLS, CAPABILITIES, EDUCATION_LINE, handle, ICONS, INSTRUCTIONS, modernVersion, PROMPTS, SERVER_NAME, SERVER_VERSION, visibleTools, type Fetcher } from "./server";

export const MCP_PATH = "/mcp";

const png = (base64: string) => () => Uint8Array.from(atob(base64), (c) => c.charCodeAt(0));
/** Paths of the server's own icons (generated by scripts/write-mcp-icons.mjs). */
const ICON_FILES: Record<string, { type: string; body: () => BodyInit }> = {
  "/favicon.ico": { type: "image/png", body: png(ICON_PNG_64_BASE64) },
  "/icon.png": { type: "image/png", body: png(ICON_PNG_512_BASE64) },
  "/icon.svg": { type: "image/svg+xml", body: () => ICON_SVG },
};
const MAX_BODY_BYTES = 64 * 1024;

const CORS: Record<string, string> = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type, Accept, Authorization, MCP-Protocol-Version, Mcp-Method, Mcp-Name, Mcp-Session-Id, Last-Event-ID",
  "Access-Control-Max-Age": "86400",
};

const json = (body: unknown, status = 200): Response =>
  new Response(JSON.stringify(body), { status, headers: { ...CORS, "Content-Type": "application/json" } });

const rpcError = (code: number, message: string, status: number): Response =>
  json({ jsonrpc: "2.0", id: null, error: { code, message } }, status);

import { CONNECT_URL } from "../core/links";
/** The connector's page on the website: setup steps for each assistant. */
export const CONNECT_PAGE = CONNECT_URL;

const about = (): string => [
  "ATLAS Explain MCP server",
  "",
  `Add this address to an AI assistant that supports MCP connectors: <this host>${MCP_PATH}`,
  `Tools: ${visibleTools().map((t) => t.name).join(", ")}. Read-only, free, no sign-in.`,
  `Setup: ${CONNECT_PAGE}`,
  "",
  EDUCATION_LINE,
].join("\n");

/** The registry name, as in server.json. */
export const REGISTRY_NAME = "io.github.MISHHF93/atlas-explain";

/**
 * A server card: what this server is and offers, readable without connecting (MCP server cards, SEP-1649 and
 * SEP-2127, still drafts; served at the paths those drafts and current deployments use). Built from the same
 * TOOLS and PROMPTS the server answers with, so it can never disagree with them.
 */
export function serverCard(origin: string) {
  return {
    $schema: "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
    name: REGISTRY_NAME,
    title: "ATLAS Explain",
    description: "Your money and the economy in plain words: official rates, inflation, mortgages, savings, prices.",
    version: SERVER_VERSION,
    websiteUrl: CONNECT_PAGE,
    repository: { url: "https://github.com/MISHHF93/atlas-explain", source: "github" },
    icons: ICONS,
    remotes: [{ type: "streamable-http", url: `${origin}${MCP_PATH}` }],
    serverInfo: { name: SERVER_NAME, title: "ATLAS Explain", version: SERVER_VERSION },
    protocolVersions: ALL_PROTOCOLS,
    authentication: { required: false },
    capabilities: CAPABILITIES,
    instructions: INSTRUCTIONS,
    tools: visibleTools().map((t) => ({ name: t.name, title: t.title, description: t.description, annotations: t.annotations })),
    prompts: PROMPTS.map((p) => ({ name: p.name, title: p.title, description: p.description })),
  };
}
const CARD_PATHS = new Set(["/.well-known/mcp/server-card.json", "/.well-known/mcp.json", `${MCP_PATH}/server-card`]);

/**
 * Origin check against DNS rebinding (required by the transport spec). The server is public and
 * read-only, so any https site (or an app with no web origin) may call it; a plain-http page that
 * isn't this computer is the rebinding pattern, and gets 403.
 */
export function originAllowed(origin: string | null): boolean {
  if (!origin || origin === "null") return true;
  try {
    const u = new URL(origin);
    if (u.protocol !== "http:") return true;
    return ["localhost", "127.0.0.1", "[::1]"].includes(u.hostname);
  } catch {
    return false;
  }
}

/** Mcp-Name may carry a Base64 sentinel: =?base64?...?= (MCP 2026-07-28, Value Encoding). */
function headerValue(v: string | null): string | null {
  if (v == null) return null;
  const m = /^=\?base64\?(.*)\?=$/.exec(v);
  if (!m) return v;
  try {
    return new TextDecoder().decode(Uint8Array.from(atob(m[1]!), (c) => c.charCodeAt(0)));
  } catch {
    return null;
  }
}

/** Header checks for modern (2026-07-28) requests: the mirrored headers must be present and match the body. */
function headerMismatch(request: Request, message: { method?: string; params?: Record<string, unknown> }, version: string): string | null {
  const h = request.headers;
  if (h.get("MCP-Protocol-Version") !== version) return `MCP-Protocol-Version header must be "${version}", as in _meta`;
  if (h.get("Mcp-Method") !== message.method) return `Mcp-Method header must be "${String(message.method)}"`;
  const named = message.method === "tools/call" || message.method === "prompts/get" ? message.params?.name : message.method === "resources/read" ? message.params?.uri : undefined;
  if (named !== undefined && headerValue(h.get("Mcp-Name")) !== String(named)) return `Mcp-Name header must match "${String(named)}"`;
  return null;
}

/**
 * `onCall` hears one count per tool call or new connection (src/mcp/stats.ts), after the answer is ready.
 * It never sees the question or the answer, and a failure in it never changes the response.
 */
export async function handleHttp(request: Request, fetcher: Fetcher, onCall?: (e: CallEvent) => void): Promise<Response> {
  const url = new URL(request.url);
  if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: CORS });
  if (!originAllowed(request.headers.get("Origin"))) return rpcError(-32600, "Forbidden origin", 403);

  // The server's own icons, so directories and clients that read a favicon from this address find one.
  const icon = ICON_FILES[url.pathname];
  if (icon && (request.method === "GET" || request.method === "HEAD")) {
    return new Response(request.method === "HEAD" ? null : icon.body(), { headers: { ...CORS, "Content-Type": icon.type, "Cache-Control": "public, max-age=86400" } });
  }

  if (request.method === "GET" || request.method === "HEAD") {
    if (CARD_PATHS.has(url.pathname)) {
      const body = request.method === "HEAD" ? null : JSON.stringify(serverCard(url.origin), null, 2);
      return new Response(body, { headers: { ...CORS, "Content-Type": "application/json", "Cache-Control": "public, max-age=3600" } });
    }
    // For uptime monitors: answers without touching any data source.
    if (url.pathname === "/health") return json({ ok: true, name: SERVER_NAME, version: SERVER_VERSION });
  }

  // A person opening the address in a browser gets the setup page, not protocol text. MCP clients
  // never ask for text/html (they send application/json or text/event-stream), so they are unaffected.
  const accept = request.headers.get("Accept") ?? "";
  if (request.method === "GET" && (url.pathname === "/" || url.pathname === MCP_PATH) && accept.includes("text/html") && !accept.includes("text/event-stream")) {
    return new Response(null, { status: 302, headers: { ...CORS, Location: CONNECT_PAGE } });
  }

  if (url.pathname !== MCP_PATH) {
    if (request.method === "GET" && url.pathname === "/") {
      return new Response(about().replace("<this host>", url.origin), { headers: { ...CORS, "Content-Type": "text/plain; charset=utf-8" } });
    }
    return new Response("Not found", { status: 404, headers: CORS });
  }

  // No server-to-client stream is offered, so GET (and DELETE of a session) is not allowed.
  if (request.method !== "POST") return new Response("Method not allowed", { status: 405, headers: { ...CORS, Allow: "POST, OPTIONS" } });

  // Only reject a header that is not a version at all. A newer, well-formed version is answered
  // anyway: these tools are plain request/response, and a 400 here makes clients such as Claude
  // fall back to an OAuth sign-in this server doesn't have ("Couldn't register").
  const headerVersion = request.headers.get("MCP-Protocol-Version");
  if (headerVersion && !/^\d{4}-\d{2}-\d{2}$/.test(headerVersion.trim())) {
    return rpcError(-32600, `Invalid MCP-Protocol-Version: ${headerVersion}`, 400);
  }

  const raw = await request.text();
  if (raw.length > MAX_BODY_BYTES) return rpcError(-32600, "Request too large", 413);
  let message: unknown;
  try {
    message = JSON.parse(raw);
  } catch {
    return rpcError(-32700, "Parse error", 400);
  }
  if (Array.isArray(message) || typeof message !== "object" || message === null) {
    return rpcError(-32600, "Send one JSON-RPC message per request", 400);
  }

  const msg = message as Parameters<typeof handle>[0];
  const version = modernVersion(msg);
  if (version !== null && msg.id !== undefined && msg.id !== null) {
    const problem = headerMismatch(request, msg, version);
    if (problem) return json({ jsonrpc: "2.0", id: msg.id, error: { code: -32020, message: `Header mismatch: ${problem}` } }, 400);
  }
  const reply = await handle(msg, fetcher);
  if (onCall) {
    try {
      const e = eventOf(msg as { method?: string; params?: Record<string, unknown> }, reply as { error?: unknown; result?: unknown } | null, request.headers.get("User-Agent"));
      if (e) onCall(e);
    } catch {
      /* counting never affects the answer */
    }
  }
  // Notifications and responses from the client get 202 with no body.
  if (!reply) return new Response(null, { status: 202, headers: CORS });
  const { status, ...body } = reply;
  return json(body, status ?? 200);
}
