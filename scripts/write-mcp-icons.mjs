// Renders public/app-icon.svg (full-bleed, safe-zone mark) into the connector server's own icons and embeds them in
// src/mcp/icon-data.ts, so the server serves /favicon.ico, /icon.png and /icon.svg from its own address.
// Claude's directory and other clients read a server's icon from its own origin, and every client
// supports PNG (SVG is optional in the MCP spec).
//   node scripts/write-mcp-icons.mjs      (needs Chrome; rerun when the logo changes)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { launchChrome } from "../store/src/cdp.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const svg = readFileSync(join(root, "public", "app-icon.svg"), "utf8");
const page = (size) =>
  `data:text/html;base64,${Buffer.from(`<!doctype html><html><body style="margin:0;background:transparent"><img src="data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}" width="${size}" height="${size}" style="display:block"></body></html>`).toString("base64")}`;

const chrome = await launchChrome(9335);
const png = {};
try {
  for (const size of [512, 64]) {
    const tab = await chrome.open(size, size, 1);
    await tab.goto(page(size), 600);
    png[size] = await tab.png();
    await tab.close();
  }
} finally {
  await chrome.close();
}

writeFileSync(
  join(root, "src", "mcp", "icon-data.ts"),
  `// Generated by scripts/write-mcp-icons.mjs from public/app-icon.svg. Do not edit by hand.\n` +
    `export const ICON_SVG = ${JSON.stringify(svg.trim())};\n` +
    `export const ICON_PNG_512_BASE64 = "${png[512].toString("base64")}";\n` +
    `export const ICON_PNG_64_BASE64 = "${png[64].toString("base64")}";\n`,
);
console.log(`src/mcp/icon-data.ts: svg ${svg.length}B, png512 ${png[512].length}B, png64 ${png[64].length}B`);
