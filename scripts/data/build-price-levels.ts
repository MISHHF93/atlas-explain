/**
 * Builds src/data/price-levels.json: each country's official consumer price index as yearly averages, for the
 * inflation calculator (src/core/inflation.ts). Past years don't change, so this runs once a year (after January,
 * when the last full year's average is published), not on a schedule:
 *
 *   node scripts/data/build-price-levels.ts
 *
 * Sources (all free, no key; licences in docs/legal/DATA_SOURCES.md):
 *   US  BLS CPI-U all items, U.S. city average (CUUR0000SA0), annual averages (M13) from the BLS bulk file, 1913 on. Public domain.
 *   CA  Statistics Canada table 18-10-0005-01, all-items CPI, annual average (vector 41693271), 1914 on. Open Licence.
 *   UK  ONS CPI index, all items (D7BT, MM23), yearly, 1988 on (the CPI starts in 1988). Open Government Licence.
 *   EA  ECB data portal HICP, euro area (changing composition), annual index, 1997 on. Reuse with the ECB credited.
 */
import { writeFileSync } from "node:fs";

const UA = "ATLAS Explain data job (https://atlas-explain.web.app)";
const get = async (url: string, init?: RequestInit) => {
  const r = await fetch(url, { ...init, headers: { "User-Agent": UA, ...(init?.headers ?? {}) } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r;
};
type Values = Record<string, number>;

async function us(): Promise<Values> {
  // The BLS bulk file for all-items CPI (tab-separated: series_id, year, period, value, footnotes). It carries the
  // official annual averages (period M13) and, unlike the keyless API, has no daily request limit.
  const text = await (await get("https://download.bls.gov/pub/time.series/cu/cu.data.1.AllItems")).text();
  const out: Values = {};
  for (const line of text.split(/\r?\n/)) {
    const [id, year, period, value] = line.split(/\t/).map((c) => c.trim());
    if (id === "CUUR0000SA0" && period === "M13" && year && value) out[year] = Number(value);
  }
  return out;
}

async function ca(): Promise<Values> {
  const body = (await (await get("https://www150.statcan.gc.ca/t1/wds/rest/getDataFromVectorsAndLatestNPeriods", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify([{ vectorId: 41693271, latestN: 300 }]) })).json()) as { status: string; object: { vectorDataPoint: { refPer: string; value: number }[] } }[];
  if (body[0]?.status !== "SUCCESS") throw new Error("Statistics Canada: no data");
  return Object.fromEntries(body[0].object.vectorDataPoint.map((p) => [p.refPer.slice(0, 4), p.value]));
}

async function uk(): Promise<Values> {
  const body = (await (await get("https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/d7bt/mm23/data")).json()) as { years: { date: string; value: string }[] };
  return Object.fromEntries(body.years.map((y) => [y.date, Number(y.value)]));
}

async function ea(): Promise<Values> {
  const csv = await (await get("https://data-api.ecb.europa.eu/service/data/HICP/A.U2.N.000000.4D0.INX?format=csvdata")).text();
  const rows = csv.trim().split("\n").slice(1).map((l) => l.split(","));
  return Object.fromEntries(rows.map((c) => [c[7]!, Number(c[8])]));
}

const lastYear = new Date().getUTCFullYear() - 1;
const keep = (v: Values) => Object.fromEntries(Object.entries(v).filter(([y, n]) => /^\d{4}$/.test(y) && Number(y) <= lastYear && Number.isFinite(n) && n > 0).sort(([a], [b]) => a.localeCompare(b)));
const [US, CA, UK, EA] = (await Promise.all([us(), ca(), uk(), ea()])).map(keep) as [Values, Values, Values, Values];

const file = {
  note: "Generated by scripts/data/build-price-levels.ts. Yearly averages of each official consumer price index; only ratios between years are used.",
  generatedAt: new Date().toISOString(),
  series: {
    US: { name: "US consumer price index (CPI-U, all items, U.S. city average)", currency: "USD", source: "U.S. Bureau of Labor Statistics", sourceUrl: "https://www.bls.gov/cpi/", licence: "Public domain (US government work). Credit the source.", base: "1982-84 = 100", values: US },
    CA: { name: "Canada consumer price index (all items)", currency: "CAD", source: "Statistics Canada, table 18-10-0005-01", sourceUrl: "https://www150.statcan.gc.ca/t1/tbl1/en/tv.action?pid=1810000501", licence: "Statistics Canada Open Licence. Credit: Source: Statistics Canada, table 18-10-0005-01.", base: "2002 = 100", values: CA },
    UK: { name: "UK consumer prices index (CPI, all items)", currency: "GBP", source: "Office for National Statistics", sourceUrl: "https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/d7bt/mm23", licence: "Open Government Licence v3.0. Credit: Source: Office for National Statistics.", base: "2015 = 100", values: UK },
    EA: { name: "Euro-area harmonised index of consumer prices (HICP, all items)", currency: "EUR", source: "European Central Bank (Eurostat HICP)", sourceUrl: "https://data.ecb.europa.eu/data/datasets/HICP", licence: "Free to reuse with credit to the European Central Bank.", base: "2025 = 100", values: EA },
  },
};
for (const [k, s] of Object.entries(file.series)) {
  const years = Object.keys(s.values);
  if (years.length < 20) throw new Error(`${k}: only ${years.length} years`);
  console.log(`${k}: ${years[0]}–${years.at(-1)} (${years.length} years)`);
}
writeFileSync("src/data/price-levels.json", JSON.stringify(file, null, 1) + "\n");
console.log("wrote src/data/price-levels.json");
